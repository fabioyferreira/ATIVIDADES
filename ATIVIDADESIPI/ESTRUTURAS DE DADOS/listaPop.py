'''Listas (remoção) - Exercício

Você está ajudando a organizar uma sala de aula virtual. A lista alunos
contém todos os nomes cadastrados:
alunos = ["Ana", "Bruno", "Carlos", "Daniela", "Eduardo"]
Sabendo que os alunos Bruno e Daniela não participaram da aula,
remova-os da lista usando pop() e mostre a lista final de alunos presentes.
'''

aluno = ['ana', 'Bruno', 'Carlos', 'Daniela', 'Eduardo']
print(f'{aluno}')
aluno.pop(1)
print(f'{aluno}')
aluno.pop(2)
print(f'{aluno}')